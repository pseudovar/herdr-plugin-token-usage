import { chmodSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { PLUGIN_ID, configDir, pluginRoot, stateDir } from "../env.ts";

function sq(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

/**
 * Write stable launchers into the state dir. herdr's tab-bar commands get no
 * HERDR_PLUGIN_* environment and run under `/bin/sh -lc`, and GitHub-installed
 * plugin roots change on update, so the startup hook rewrites these with
 * absolute paths every time the server starts.
 */
export function writeShims(): { statusLine: string; tu: string } {
  const dir = join(stateDir(), "bin");
  mkdirSync(dir, { recursive: true });
  const node = process.execPath;
  const cli = join(pluginRoot(), "src", "cli.ts");
  const env = [
    `export HERDR_PLUGIN_STATE_DIR=${sq(stateDir())}`,
    `export HERDR_PLUGIN_CONFIG_DIR=${sq(configDir())}`,
    `export HERDR_PLUGIN_ROOT=${sq(pluginRoot())}`,
  ].join("\n");
  const header = `#!/bin/sh\n# Generated by the ${PLUGIN_ID} herdr plugin; rewritten on every herdr start.\n`;
  const statusLine = join(dir, "tu-status");
  writeFileSync(
    statusLine,
    `${header}${env}\nexec ${sq(node)} --disable-warning=ExperimentalWarning ${sq(cli)} status-line "$@"\n`,
  );
  chmodSync(statusLine, 0o755);
  const tu = join(dir, "tu");
  writeFileSync(tu, `${header}${env}\nexec ${sq(node)} --disable-warning=ExperimentalWarning ${sq(cli)} "$@"\n`);
  chmodSync(tu, 0o755);
  return { statusLine, tu };
}

export function statusShimPath(): string {
  return join(stateDir(), "bin", "tu-status");
}
